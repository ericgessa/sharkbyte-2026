"""LIVE end-to-end check against the Supabase project in server/.env.

    python -m scripts.e2e_live        (run from server/)

Runs the real app in-process (real Supabase auth + database, no mocks):
  throwaway user -> sign in -> create workout -> authenticate WebSocket ->
  stream 5 SIMULATED squats -> finish -> read the rows back from Postgres.
Then deletes the user (cascade removes its profile, session and reps).
Pose data is generated by app.simulation; it is not real camera data.
"""

from __future__ import annotations

import json
import os
import secrets
import sys
import time
from uuid import uuid4

from fastapi.testclient import TestClient
from supabase import create_client

from app.main import create_app
from app.services.database import DatabaseConfigError, get_client
from app.simulation import squat_messages

REPS = 5
results: list[tuple[str, bool]] = []


def check(name: str, ok: bool) -> None:
    results.append((name, ok))
    print(f"{'ok  ' if ok else 'FAIL'}  {name}")


def sign_in_token(email: str, password: str) -> str:
    """Get a real user access token using a *separate* client (keeps the main client's state clean)."""
    key = os.environ.get("SUPABASE_PUBLISHABLE_KEY", "").strip()
    if not key or key.startswith("your-"):
        key = os.environ["SUPABASE_SECRET_KEY"].strip()
    anon = create_client(os.environ["SUPABASE_URL"].strip(), key)
    return anon.auth.sign_in_with_password({"email": email, "password": password}).session.access_token


def main() -> int:
    try:
        admin = get_client()
    except DatabaseConfigError as exc:
        print(f"CONFIG ERROR: {exc}")
        return 2

    email, password = f"e2e-{uuid4().hex[:12]}@example.com", secrets.token_urlsafe(24)
    user = admin.auth.admin.create_user({"email": email, "password": password, "email_confirm": True}).user
    print(f"created throwaway user {user.id}")
    try:
        token = sign_in_token(email, password)
        headers = {"Authorization": f"Bearer {token}"}

        with TestClient(create_app()) as client:
            check("request without a token is rejected (401)", client.post("/api/workouts", json={}).status_code == 401)

            r = client.post("/api/workouts", json={"exercise": "squat"}, headers=headers)
            check("create workout (201)", r.status_code == 201)
            sid = r.json()["session_id"]

            with client.websocket_connect(f"/ws/workouts/{sid}") as ws:
                ws.send_text(json.dumps({"schema_version": 1, "type": "auth", "access_token": token}))
                check("websocket authenticated", ws.receive_json()["type"] == "session_ready")
                # Last two reps are clearly shallower: the coach should say something once.
                for msg in squat_messages(sid, reps=REPS, depths=[85, 85, 85, 98, 98]):
                    ws.send_text(json.dumps(msg))
                events = [ws.receive_json() for _ in range(REPS + 1)]
            reps_seen = [e for e in events if e["type"] == "rep_completed"]
            feedback = [e for e in events if e["type"] == "coaching_feedback"]
            check(f"{REPS} rep_completed events", [e["rep_count"] for e in reps_seen] == list(range(1, REPS + 1)))
            check("one coaching_feedback (reduced_depth) sent", len(feedback) == 1 and feedback[0]["issue_code"] == "reduced_depth")

            r = client.post(f"/api/workouts/{sid}/finish", headers=headers)
            check("finish workout (200, completed)", r.status_code == 200 and r.json()["status"] == "completed")
            check(f"API reports total_reps == {REPS}", r.json().get("total_reps") == REPS)

        # Read back straight from Postgres, bypassing our API.
        reps = admin.table("repetitions").select("rep_number, metrics").eq("session_id", sid).order("rep_number").execute().data
        check(f"{REPS} repetition rows saved in Supabase", [x["rep_number"] for x in reps] == list(range(1, REPS + 1)))
        check("rep metrics stored as JSON", all("min_knee_angle_deg" in x["metrics"] for x in reps))
        coaching = admin.table("coaching_events").select("rep_number,issue_code,message,action").eq("session_id", sid).execute().data
        check(
            "coaching event saved in Supabase and matches what the user saw",
            len(coaching) == 1 and coaching[0]["issue_code"] == "reduced_depth" and coaching[0]["rep_number"] == REPS
            and coaching[0]["action"] == "send_feedback" and bool(feedback) and coaching[0]["message"] == feedback[0]["message"],
        )
        row = admin.table("workout_sessions").select("status,total_reps,ended_at,user_id").eq("id", sid).single().execute().data
        check("session row completed with ended_at", row["status"] == "completed" and bool(row["ended_at"]))
        check("session row total_reps and owner correct", row["total_reps"] == REPS and row["user_id"] == user.id)
    finally:
        admin.auth.admin.delete_user(user.id)
        time.sleep(0.5)
        left = admin.table("workout_sessions").select("id", count="exact").eq("user_id", user.id).limit(0).execute().count
        print(f"deleted throwaway user; leftover sessions: {left}")

    failed = [n for n, ok in results if not ok]
    print("\nE2E FAILED: " + "; ".join(failed) if failed else "\nE2E passed")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
