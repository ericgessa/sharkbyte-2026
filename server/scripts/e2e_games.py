"""LIVE end-to-end check of GRIT Games against the Supabase project in server/.env.

    python -m scripts.e2e_games        (run from server/)

Needs the games migration applied first (supabase/migrations/20261108000001_grit_games.sql); without it this script
stops at the first step and says so. Runs the real app in-process (real Supabase auth and database, no mocks) with two
throwaway users:
  * Alice: a camera-style solo race (5 SIMULATED squats) saved as a result, a faster second race (personal best), a
    history, best, and the Row Level Security rules (Bob cannot see Alice's rows).
  * Alice and Bob: a real 1v1 room over WebSockets (create, join, ready, 3-2-1, race, winner), then the saved race.
Then deletes everything it created (users cascade; the finished-race rows are deleted explicitly).
Pose data is generated by app.simulation; it is not real camera data.
"""

from __future__ import annotations

import json
import os
import secrets
import sys
import time
from uuid import uuid4

from fastapi.testclient import TestClient
from supabase import create_client

from app.main import create_app
from app.services.database import DatabaseConfigError, get_client
from app.services.games_db import GameStore
from app.simulation import squat_messages
from scripts._cleanup import arm_watchdog, purge_tiger_readings

results: list[tuple[str, bool]] = []


def check(name: str, ok: bool) -> None:
    results.append((name, ok))
    print(f"{'ok  ' if ok else 'FAIL'}  {name}")


def user_client(email: str, password: str):
    key = os.environ.get("SUPABASE_PUBLISHABLE_KEY", "").strip()
    if not key or key.startswith("your-"):
        key = os.environ["SUPABASE_SECRET_KEY"].strip()
    anon = create_client(os.environ["SUPABASE_URL"].strip(), key)
    return anon, anon.auth.sign_in_with_password({"email": email, "password": password}).session.access_token


def play_workout(client: TestClient, token: str, exercise: str, reps: int, depths=None) -> str:
    """A real workout over the real WebSocket, finished through the API. Returns the session id."""
    headers = {"Authorization": f"Bearer {token}"}
    sid = client.post("/api/workouts", json={"exercise": exercise}, headers=headers).json()["session_id"]
    with client.websocket_connect(f"/ws/workouts/{sid}") as ws:
        ws.send_text(json.dumps({"schema_version": 1, "type": "auth", "access_token": token}))
        ws.receive_json()
        for msg in squat_messages(sid, reps=reps, depths=depths):
            ws.send_text(json.dumps(msg))
        got = 0
        while got < reps:
            if ws.receive_json()["type"] == "rep_completed":
                got += 1
    assert client.post(f"/api/workouts/{sid}/finish", headers=headers).status_code == 200
    return sid


def main() -> int:
    try:
        admin = get_client()
    except DatabaseConfigError as exc:
        print(f"CONFIG ERROR: {exc}")
        return 2
    if not GameStore(admin).ping():
        print("The GRIT Games tables are not in this Supabase project yet.")
        print("Apply supabase/migrations/20261108000001_grit_games.sql (Dashboard > SQL Editor > paste > Run), then run this again.")
        return 2

    users: dict[str, dict] = {}
    for name in ("alice", "bob"):
        email, password = f"e2e-games-{name}-{uuid4().hex[:8]}@example.com", secrets.token_urlsafe(24)
        u = admin.auth.admin.create_user({"email": email, "password": password, "email_confirm": True}).user
        users[name] = {"id": u.id, "email": email, "password": password}
    workouts: list[str] = []
    room_ids: set[str] = set()

    def cleanup() -> None:
        purge_tiger_readings(workouts, settle_s=0.5)
        for rid in room_ids:
            admin.table("game_rooms").delete().eq("id", rid).execute()
        for u in users.values():
            admin.auth.admin.delete_user(u["id"])
        print("deleted throwaway users and their rows")

    watchdog = arm_watchdog(240, cleanup)
    print(f"created throwaway users {users['alice']['id'][:8]}.. and {users['bob']['id'][:8]}..")
    try:
        a_db, a_tok = user_client(users["alice"]["email"], users["alice"]["password"])
        b_db, b_tok = user_client(users["bob"]["email"], users["bob"]["password"])
        A, B = {"Authorization": f"Bearer {a_tok}"}, {"Authorization": f"Bearer {b_tok}"}

        with TestClient(create_app()) as client:
            # ---- solo results
            s1 = play_workout(client, a_tok, "squat", 5)
            workouts.append(s1)
            body = {"game": "rep_racer", "mode": "solo", "exercise": "squat", "workout_session_id": s1, "duration_ms": 1, "target_reps": 5, "time_limit_s": 60}
            r = client.post("/api/games/results", json=body, headers=A)
            j = r.json() if r.status_code < 400 else {}
            check("solo race result saved (201)", r.status_code == 201)
            check("server counted 5 reps and the target was reached", j.get("valid_reps") == 5 and j.get("completed") is True)
            check("completion time comes from the server, not the claimed 1 ms", j.get("duration_ms", 0) > 1 or len(j.get("rep_times_ms", [])) == 5)
            check("first race: no previous best", (j.get("personal_best") or {}).get("has_previous") is False)
            check("saving the same workout again returns the same result",
                  client.post("/api/games/results", json=body, headers=A).json().get("id") == j.get("id"))

            s2 = play_workout(client, a_tok, "squat", 5)
            workouts.append(s2)
            j2 = client.post("/api/games/results", json={**body, "mode": "personal_best", "workout_session_id": s2}, headers=A).json()
            check("second race compares with the first", (j2.get("personal_best") or {}).get("has_previous") is True)
            best = client.get("/api/games/best", params={"game": "rep_racer", "exercise": "squat", "target_reps": 5}, headers=A).json()
            check("best returns a ghost with recorded rep times", best["attempts"] == 2 and len(best["best"]["rep_times_ms"]) == 5)

            hist = client.get("/api/games/results", headers=A).json()
            check("history lists both, newest first", len(hist) == 2 and hist[0]["mode"] == "personal_best")

            # ---- who can see what
            check("Bob's history is empty", client.get("/api/games/results", headers=B).json() == [])
            check("Bob cannot open Alice's result", client.get(f"/api/games/results/{j['id']}", headers=B).status_code == 404)
            check("Bob cannot attach a result to Alice's workout", client.post("/api/games/results", json=body, headers=B).status_code == 404)
            own = a_db.postgrest.auth(a_tok).table("game_results").select("id").execute().data
            others = b_db.postgrest.auth(b_tok).table("game_results").select("id").execute().data
            check("Row Level Security: Alice reads her 2 rows, Bob reads none", len(own) == 2 and others == [])
            denied = False
            try:
                a_db.postgrest.auth(a_tok).table("game_results").insert({"user_id": users["alice"]["id"], "game": "rep_racer", "mode": "solo", "exercise": "squat", "valid_reps": 99, "duration_ms": 1}).execute()
            except Exception:
                denied = True
            check("a signed-in client cannot write results directly", denied)

        # ---- a live 1v1 over WebSockets (a fresh app, like a restarted server)
        with TestClient(create_app()) as client:
            room = client.post("/api/games/rooms", json={"exercise": "squat", "target_reps": 3, "time_limit_s": 30, "display_name": "Alice"}, headers=A).json()
            code = room["code"]
            check("room created with a code", len(code) == 6)
            check("Bob joins", client.post(f"/api/games/rooms/{code}/join", json={"display_name": "Bob"}, headers=B).status_code == 200)

            def recv_until(ws, kind: str, limit: int = 800) -> dict:
                for _ in range(limit):
                    m = ws.receive_json()
                    if m["type"] == kind:
                        return m
                raise AssertionError(f"never saw {kind}")

            with client.websocket_connect(f"/ws/games/rooms/{code}") as wa, client.websocket_connect(f"/ws/games/rooms/{code}") as wb:
                wa.send_text(json.dumps({"schema_version": 1, "type": "auth", "access_token": a_tok}))
                wb.send_text(json.dumps({"schema_version": 1, "type": "auth", "access_token": b_tok}))
                recv_until(wa, "room_state")
                recv_until(wb, "room_state")
                for w in (wa, wb):
                    w.send_text(json.dumps({"schema_version": 1, "type": "ready", "ready": True}))
                recv_until(wa, "race_started")
                recv_until(wb, "race_started")
                check("synchronised countdown, then the race started for both", True)
                frames = []
                for m in squat_messages("x", reps=3):
                    m.pop("session_id")
                    frames.append(m)
                for m in frames:
                    wa.send_text(json.dumps(m))
                done_a = recv_until(wa, "race_finished")
                done_b = recv_until(wb, "race_finished")
                check("server declared Alice the winner on both screens", done_a["winner_id"] == users["alice"]["id"] and done_b["winner_id"] == users["alice"]["id"])
            time.sleep(4)  # the race is saved in the background
            mine = [r for r in client.get("/api/games/results", headers=A).json() if r["mode"] == "multiplayer"]
            theirs = [r for r in client.get("/api/games/results", headers=B).json() if r["mode"] == "multiplayer"]
            check("the race was saved for both players", len(mine) == 1 and len(theirs) == 1 and mine[0]["room_id"] == theirs[0]["room_id"])
            if mine:
                room_ids.add(mine[0]["room_id"])
                workouts.extend(r["workout_session_id"] for r in mine + theirs if r["workout_session_id"])
                check("Alice's side: 3 reps, finished; Bob's side: not finished", mine[0]["completed"] is True and mine[0]["valid_reps"] == 3 and theirs[0]["completed"] is False)
                saved = client.get(f"/api/games/races/{mine[0]['room_id']}", headers=A)
                check("the saved race is readable by its players", saved.status_code == 200 and saved.json()["winner_id"] == users["alice"]["id"])
                check("...and not by anyone else", client.get(f"/api/games/races/{mine[0]['room_id']}", headers={"Authorization": "Bearer nope"}).status_code == 401)
    finally:
        watchdog.cancel()
        cleanup()

    failed = [n for n, ok in results if not ok]
    print("\nGames E2E passed" if not failed else f"\nGames E2E FAILED: {failed}")
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
